set_project("libht")
set_xmakever("3.0.0")
set_allowedmodes("debug", "release")
add_rules("mode.debug", "mode.release")
includes("xmake/compile_commands.lua")
add_rules("libht.compile_commands")
option("tests")
    set_default(false)
option_end()
option("wire_backend")
    set_default("zpp")
    set_values("zpp", "pfr")
option_end()
option("wire_standard")
    set_default("cxx20")
    set_values("cxx20", "cxx23")
option_end()
option("eigen_dir")
    set_default("lib/eigen")
option_end()
option("python")
    set_default("python3")
option_end()

local root = os.projectdir()
target("serialization")
    set_kind("headeronly")
    on_load(function (target)
        import("build", {rootdir = os.projectdir()}).codec(target, os.projectdir())
    end)
target_end()
target("crc")
    set_kind("headeronly")
    add_includedirs("utility/crc/include", {public = true})
    set_languages("cxx20")
target_end()
target("rmlink")
    set_kind("static")
    set_languages("cxx20")
    add_deps("serialization", "crc")
    add_includedirs("protocol/rmlink/include", {public = true})
    add_files("protocol/rmlink/src/*.cpp")
target_end()
for _, name in ipairs({"pid", "leso", "ladrc", "rls", "wave"}) do
    target(name)
        set_kind("headeronly")
        set_languages("cxx23")
        add_includedirs("algorithm", "algorithm/" .. name, {public = true})
        if name == "ladrc" then add_deps("leso") end
        if name == "rls" then
            on_load(function (target)
                import("core.project.config")
                local eigen = path.absolute(config.get("eigen_dir"), os.projectdir())
                assert(os.isfile(path.join(eigen, "Eigen/Core")), "RLS requires Eigen; set --eigen_dir")
                target:add("sysincludedirs", eigen, {public = true})
            end)
        end
    target_end()
end

if has_config("tests") then
local function host(name, sources, deps, standard, is_example)
    target(name)
        set_kind("binary")
        set_group("tests")
        set_languages(standard or "cxx23")
        set_warnings("allextra", "pedantic", "error")
        add_files(table.unpack(sources))
        add_deps(table.unpack(deps))
        if is_host("linux") then add_syslinks("pthread") end
        if not is_example then
            on_load(function (target)
                import("lib.detect.find_package")
                local gtest = find_package("pkgconfig::gtest_main")
                assert(gtest, "Set PKG_CONFIG_PATH to GoogleTest or install gtest")
                target:add("sysincludedirs", gtest.includedirs)
                target:add("linkdirs", gtest.linkdirs)
                target:add("links", gtest.links)
                target:add("defines", gtest.defines)
            end)
        end
        add_tests("run")
    target_end()
end
host("algorithm-tests", {"tests/algorithm_tests.cpp"}, {"pid", "leso", "ladrc", "rls", "wave"})
host("crc-tests", {"utility/crc/tests/crc_tests.cpp"}, {"crc"}, "cxx20")
local standard = get_config("wire_standard") or "cxx20"
host("wire-tests", {"utility/serialization/tests/codec_tests.cpp"}, {"serialization"}, standard)
host("wire-example", {"utility/serialization/tests/usage_example.cpp"}, {"serialization"}, standard, true)
host("rmlink-wire-tests", {"protocol/rmlink/tests/wire_tests.cpp"}, {"rmlink"}, "cxx20")
host("rmlink-core-tests", {"protocol/rmlink/tests/core_tests.cpp", "protocol/rmlink/tests/shared_codec_tests.cpp"}, {"rmlink"}, "cxx20")
host("rmlink-example", {"protocol/rmlink/examples/basic.cpp"}, {"rmlink"}, "cxx20", true)

target("wire-compile-tests")
    set_kind("phony")
    set_group("tests")
    add_tests("native", {runargs = {"c++"}})
    add_tests("arm", {runargs = {"arm-none-eabi-g++", "--arm"}})
    on_test(function (target, opt)
        import("core.project.config")
        local args = {path.join(os.projectdir(), "utility/serialization/tests/compile_checks.py"),
            "--backend", config.get("wire_backend"), "--compiler"}
        for _, arg in ipairs(opt.runargs) do table.insert(args, arg) end
        local result = os.execv(config.get("python"), args, {try = true})
        return result == 0
    end)
target_end()
end

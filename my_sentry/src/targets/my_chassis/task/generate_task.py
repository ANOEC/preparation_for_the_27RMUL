#!/usr/bin/env python3
"""Generate the LibXR/FreeRTOS task framework from task.toml.

Only task scheduling belongs here.  Application behaviour stays in hand-written
TaskHooks specializations (for example chassis_task.cpp).
"""

from __future__ import annotations

import argparse
from dataclasses import dataclass
from pathlib import Path
import re
import sys

try:
    import tomllib
except ModuleNotFoundError:  # Python 3.10
    import tomli as tomllib  # type: ignore[no-redef]


IDENTIFIER = re.compile(r"^[A-Za-z_][A-Za-z0-9_]*$")
PRIORITIES = {
    "IDLE": "LibXR::Thread::Priority::IDLE",
    "LOW": "LibXR::Thread::Priority::LOW",
    "MEDIUM": "LibXR::Thread::Priority::MEDIUM",
    "HIGH": "LibXR::Thread::Priority::HIGH",
    "REALTIME": "LibXR::Thread::Priority::REALTIME",
}


@dataclass(frozen=True)
class Task:
    name: str
    priority: int | str
    stack_size: int
    entry_function: str
    period_us: int | None
    trigger_sem: str | None
    daemon_timeout_ms: int | None
    parameters: tuple[str, str, str]
    custom_init: bool
    delay_start_ms: int


def fail(message: str) -> None:
    raise ValueError(message)


def identifier(value: object, field: str, task: str) -> str:
    if not isinstance(value, str) or IDENTIFIER.fullmatch(value) is None:
        fail(f"task '{task}': {field} must be a C++ identifier")
    return value


def positive_int(value: object, field: str, task: str) -> int:
    if not isinstance(value, int) or isinstance(value, bool) or value <= 0:
        fail(f"task '{task}': {field} must be a positive integer")
    return value


def parse_delay(value: object, task: str) -> int:
    if value is None or value in ("K_FOREVER", "IMMEDIATE"):
        # K_FOREVER is accepted for easy migration from the Zephyr generator.
        # The old generator created the thread suspended and started it immediately.
        return 0
    if not isinstance(value, int) or isinstance(value, bool) or value < 0:
        fail(f"task '{task}': delay_start must be a non-negative millisecond value")
    return value


def parse_task(raw: object) -> Task:
    if not isinstance(raw, dict):
        fail("every [[tasks]] item must be a table")
    name = identifier(raw.get("name"), "name", "<unknown>")
    entry = identifier(raw.get("entry_function"), "entry_function", name)
    priority = raw.get("priority")
    if isinstance(priority, str):
        if priority not in PRIORITIES:
            fail(f"task '{name}': priority must be one of {', '.join(PRIORITIES)} or an integer")
    elif not isinstance(priority, int) or isinstance(priority, bool) or not 0 <= priority <= 255:
        fail(f"task '{name}': priority must be one of {', '.join(PRIORITIES)} or an integer")

    period = raw.get("period_us")
    sem = raw.get("trigger_sem")
    if (period is None) == (sem is None):
        fail(f"task '{name}': exactly one of period_us and trigger_sem is required")
    if period is not None:
        period = positive_int(period, "period_us", name)
        if period < 1000 or period % 1000 != 0:
            fail(f"task '{name}': the FreeRTOS backend requires period_us to be a multiple of 1000")
    if sem is not None:
        sem = identifier(sem, "trigger_sem", name)

    timeout = raw.get("daemon_timeout_ms")
    if timeout is not None:
        timeout = positive_int(timeout, "daemon_timeout_ms", name)

    custom_init = raw.get("custom_init", False)
    if not isinstance(custom_init, bool):
        fail(f"task '{name}': custom_init must be true or false")

    params = raw.get("parameters", ["nullptr", "nullptr", "nullptr"])
    if not isinstance(params, list) or len(params) > 3 or not all(isinstance(item, str) for item in params):
        fail(f"task '{name}': parameters must contain at most three C++ expression strings")
    params = params + ["nullptr"] * (3 - len(params))

    options = raw.get("options", 0)
    if options not in (0, "0", None):
        fail(f"task '{name}': options is reserved; the LibXR backend currently accepts only 0")

    return Task(
        name=name,
        priority=priority,
        stack_size=positive_int(raw.get("stack_size"), "stack_size", name),
        entry_function=entry,
        period_us=period,
        trigger_sem=sem,
        daemon_timeout_ms=timeout,
        parameters=(params[0], params[1], params[2]),
        custom_init=custom_init,
        delay_start_ms=parse_delay(raw.get("delay_start"), name),
    )


def priority_cpp(value: int | str) -> str:
    if isinstance(value, str):
        return PRIORITIES[value]
    return f"static_cast<LibXR::Thread::Priority>({value})"


def header(tasks: list[Task]) -> str:
    lines = [
        "// Generated by User/task/generate_task.py. Do not edit.",
        "#pragma once",
        "",
        "#include <cstdint>",
        "#include \"semaphore.hpp\"",
        "#include \"task/task_runtime.hpp\"",
        "#include \"thread.hpp\"",
        "",
        "namespace generated::task {",
        "struct LoopContext {",
        "  void* p1;",
        "  void* p2;",
        "  void* p3;",
        "  DaemonService* daemon_service;",
        "  float dt_s;",
        "  std::uint32_t period_us;",
        "  std::uint64_t now_us;",
        "  std::uint32_t iteration;",
        "};",
        "",
        "template <typename TaskTag>",
        "struct TaskHooks;",
        "",
    ]
    sems: set[str] = set()
    for task in tasks:
        if task.trigger_sem and task.trigger_sem not in sems:
            lines.extend(["}  // namespace generated::task", f"extern LibXR::Semaphore {task.trigger_sem};", "", "namespace generated::task {"])
            sems.add(task.trigger_sem)
        lines.extend([
            f"struct {task.name}_tag {{}};",
            f"template <> struct TaskHooks<{task.name}_tag> {{",
        ])
        if task.custom_init:
            lines.append("  static void init(void* p1, void* p2, void* p3);")
        else:
            lines.extend([
                "  static void init(void*, void*, void*) {}",
            ])
        lines.extend([
            "  static void loop(const LoopContext& context);",
            "};",
            f"extern LibXR::Thread {task.name}_thread;",
            "",
        ])
    lines.extend(["}  // namespace generated::task", "", "void all_tasks_start();", ""])
    return "\n".join(lines)


def task_entry(task: Task) -> list[str]:
    service = f"&{task.name}_daemon" if task.daemon_timeout_ms is not None else "nullptr"
    period = task.period_us or 0
    lines = [
        f"void {task.entry_function}(void*)",
        "{",
    ]
    if task.delay_start_ms:
        lines.append(f"  LibXR::Thread::Sleep({task.delay_start_ms}U);")
    if task.daemon_timeout_ms is not None:
        lines.append(f"  {task.name}_daemon.Start();")
    lines.extend([
        f"  TaskHooks<{task.name}_tag>::init({task.parameters[0]}, {task.parameters[1]}, {task.parameters[2]});",
        "  std::uint64_t last_us = NowUs();",
        "  LoopContext context{",
        f"      {task.parameters[0]}, {task.parameters[1]}, {task.parameters[2]}, {service},",
        f"      0.0F, {period}U, last_us, 0U}};",
    ])
    if task.period_us is not None:
        lines.extend([
            "  LibXR::MillisecondTimestamp wake_time(",
            "      static_cast<std::uint32_t>(LibXR::Timebase::GetMilliseconds()));",
            "  for (;;)",
            "  {",
            f"    LibXR::Thread::SleepUntil(wake_time, {task.period_us // 1000}U);",
        ])
    else:
        lines.extend(["  for (;;)", "  {", f"    static_cast<void>(::{task.trigger_sem}.Wait());"])
    lines.extend([
        "    context.now_us = NowUs();",
        "    context.dt_s = static_cast<float>(context.now_us - last_us) * 1.0e-6F;",
        "    last_us = context.now_us;",
        f"    TaskHooks<{task.name}_tag>::loop(context);",
        "    ++context.iteration;",
        "  }",
        "}",
        "",
    ])
    return lines


def source(tasks: list[Task]) -> str:
    lines = [
        "// Generated by User/task/generate_task.py. Do not edit.",
        "#include \"task_generated.hpp\"",
        "",
        "#include \"timebase.hpp\"",
        "",
        "namespace generated::task {",
        "namespace {",
        "std::uint64_t NowUs()",
        "{",
        "  return static_cast<std::uint64_t>(LibXR::Timebase::GetMicroseconds());",
        "}",
        "",
    ]
    for task in tasks:
        if task.daemon_timeout_ms is not None:
            lines.append(f'DaemonService {task.name}_daemon("{task.name}", {task.daemon_timeout_ms}U);')
    lines.extend(["}  // namespace", ""])
    for task in tasks:
        lines.extend([f"LibXR::Thread {task.name}_thread;", ""])
        lines.extend(task_entry(task))
    lines.extend([
        "}  // namespace generated::task",
        "",
        "void all_tasks_start()",
        "{",
        "  static bool started = false;",
        "  if (started)",
        "  {",
        "    return;",
        "  }",
        "  started = true;",
        "  generated::task::TaskDaemon::Instance().Start();",
    ])
    for task in tasks:
        lines.extend([
            f"  generated::task::{task.name}_thread.Create(",
            f"      static_cast<void*>(nullptr), generated::task::{task.entry_function},",
            f'      "{task.name}", {task.stack_size}U, {priority_cpp(task.priority)});',
        ])
    lines.extend(["}", ""])
    return "\n".join(lines)


def write_if_changed(path: Path, content: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    if path.exists() and path.read_text(encoding="utf-8") == content:
        return
    path.write_text(content, encoding="utf-8", newline="\n")


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("config", type=Path)
    parser.add_argument("output_dir", type=Path)
    args = parser.parse_args()
    try:
        data = tomllib.loads(args.config.read_text(encoding="utf-8"))
        raw_tasks = data.get("tasks", [])
        if not isinstance(raw_tasks, list):
            fail("'tasks' must be an array of tables")
        tasks = [parse_task(item) for item in raw_tasks]
        names = [item.name for item in tasks]
        entries = [item.entry_function for item in tasks]
        if len(names) != len(set(names)):
            fail("task names must be unique")
        if len(entries) != len(set(entries)):
            fail("entry_function values must be unique")
        write_if_changed(args.output_dir / "task_generated.hpp", header(tasks))
        write_if_changed(args.output_dir / "task_generated.cpp", source(tasks))
    except (OSError, tomllib.TOMLDecodeError, ValueError) as error:
        print(f"task generator: {error}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

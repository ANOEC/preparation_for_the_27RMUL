#!/usr/bin/env python3
"""Generate LibXR/FreeRTOS task scaffolding from task.config.toml.

The TOML file is the source of truth: tasks may be periodic (``period_us``) or
event driven (``trigger_sem``), and use LibXR's named priorities.
"""

from __future__ import annotations

import argparse
from dataclasses import dataclass
from pathlib import Path
import re
import sys

try:
    import tomllib
except ModuleNotFoundError:
    import tomli as tomllib  # type: ignore[no-redef]


IDENTIFIER = re.compile(r"^[A-Za-z_][A-Za-z0-9_]*$")
PRIORITIES = {
    "IDLE": "LibXR::Thread::Priority::IDLE",
    "LOW": "LibXR::Thread::Priority::LOW",
    "MEDIUM": "LibXR::Thread::Priority::MEDIUM",
    "HIGH": "LibXR::Thread::Priority::HIGH",
    "REALTIME": "LibXR::Thread::Priority::REALTIME",
}
TASK_FIELDS = {
    "name",
    "priority",
    "stack_size",
    "entry_function",
    "daemon_timeout_ms",
    "parameters",
    "delay_start",
    "period_us",
    "trigger_sem",
    "custom_init",
}


@dataclass(frozen=True)
class Task:
    name: str
    priority: str
    stack_size: int
    entry_function: str
    daemon_timeout_ms: int | None
    parameters: tuple[str, str, str]
    period_us: int | None
    trigger_sem: str | None
    custom_init: bool
    delay_start_ms: int


def identifier(value: object, field: str, task: str = "<unknown>") -> str:
    if not isinstance(value, str) or IDENTIFIER.fullmatch(value) is None:
        raise ValueError(f"task '{task}': {field} must be a C++ identifier")
    return value


def positive_int(value: object, field: str, task: str) -> int:
    if not isinstance(value, int) or isinstance(value, bool) or value <= 0:
        raise ValueError(f"task '{task}': {field} must be a positive integer")
    return value


def parse_delay(value: object, task: str) -> int:
    if value is None or value == "IMMEDIATE":
        return 0
    if not isinstance(value, int) or isinstance(value, bool) or value < 0:
        raise ValueError(
            f"task '{task}': delay_start must be IMMEDIATE "
            "or a non-negative millisecond value"
        )
    return value


def parse_task(raw: object) -> Task:
    if not isinstance(raw, dict):
        raise ValueError("every [[tasks]] item must be a table")

    name = identifier(raw.get("name"), "name")
    unsupported_fields = sorted(set(raw) - TASK_FIELDS)
    if unsupported_fields:
        raise ValueError(
            f"task '{name}': unsupported field(s): {', '.join(unsupported_fields)}"
        )

    priority = raw.get("priority")
    if not isinstance(priority, str) or priority not in PRIORITIES:
        raise ValueError(
            f"task '{name}': priority must be one of {', '.join(PRIORITIES)}"
        )

    period_us = raw.get("period_us")
    trigger_sem = raw.get("trigger_sem")
    if (period_us is None) == (trigger_sem is None):
        raise ValueError(
            f"task '{name}': exactly one of period_us and trigger_sem is required"
        )
    if period_us is not None:
        period_us = positive_int(period_us, "period_us", name)
        if period_us < 1000 or period_us % 1000 != 0:
            raise ValueError(
                f"task '{name}': the FreeRTOS backend requires period_us "
                "to be a multiple of 1000"
            )
    if trigger_sem is not None:
        trigger_sem = identifier(trigger_sem, "trigger_sem", name)

    timeout = raw.get("daemon_timeout_ms")
    if timeout is not None:
        timeout = positive_int(timeout, "daemon_timeout_ms", name)

    custom_init = raw.get("custom_init", False)
    if not isinstance(custom_init, bool):
        raise ValueError(f"task '{name}': custom_init must be true or false")

    params = raw.get("parameters", ["nullptr", "nullptr", "nullptr"])
    if not isinstance(params, list) or len(params) > 3 or not all(
        isinstance(item, str) for item in params
    ):
        raise ValueError(
            f"task '{name}': parameters must contain at most three C++ expression strings"
        )
    params = params + ["nullptr"] * (3 - len(params))

    return Task(
        name=name,
        priority=priority,
        stack_size=positive_int(raw.get("stack_size"), "stack_size", name),
        entry_function=identifier(raw.get("entry_function"), "entry_function", name),
        daemon_timeout_ms=timeout,
        parameters=(params[0], params[1], params[2]),
        period_us=period_us,
        trigger_sem=trigger_sem,
        custom_init=custom_init,
        delay_start_ms=parse_delay(raw.get("delay_start", "IMMEDIATE"), name),
    )


def make_header(tasks: list[Task]) -> str:
    lines = [
        "// Generated by generate_task.py. Do not edit.",
        "#pragma once",
        "",
        "#include <cstdint>",
        '#include "semaphore.hpp"',
        '#include "task/task_runtime.hpp"',
        '#include "thread.hpp"',
        "",
        "namespace generated::task",
        "{",
        "struct LoopContext",
        "{",
        "  void* p1;",
        "  void* p2;",
        "  void* p3;",
        "  DaemonService* daemon_service;",
        "  float dt_s;",
        "  std::uint32_t period_us;",
        "  std::uint64_t now_us;",
        "  std::uint32_t iteration;",
        "};",
        "",
        "template <typename TaskTag>",
        "struct TaskHooks;",
        "",
    ]
    semaphores: set[str] = set()
    for task in tasks:
        if task.trigger_sem is not None and task.trigger_sem not in semaphores:
            lines += [
                "}  // namespace generated::task",
                f"extern LibXR::Semaphore {task.trigger_sem};",
                "",
                "namespace generated::task",
                "{",
            ]
            semaphores.add(task.trigger_sem)
        lines += [
            f"struct {task.name}_tag {{}};",
            f"template <> struct TaskHooks<{task.name}_tag>",
            "{",
        ]
        if task.custom_init:
            lines.append("  static void init(void* p1, void* p2, void* p3);")
        else:
            lines.append("  static void init(void*, void*, void*) {}")
        lines += [
            "  static void loop(const LoopContext& context);",
            "};",
            f"extern LibXR::Thread {task.name}_thread;",
            "",
        ]
    lines += ["}  // namespace generated::task", "", "void all_tasks_start();", ""]
    return "\n".join(lines)


def task_entry(task: Task) -> list[str]:
    daemon = f"&{task.name}_daemon" if task.daemon_timeout_ms is not None else "nullptr"
    p1, p2, p3 = task.parameters
    lines = [f"void {task.entry_function}(void*)", "{"]
    if task.delay_start_ms:
        lines.append(f"  LibXR::Thread::Sleep({task.delay_start_ms}U);")
    if task.daemon_timeout_ms is not None:
        lines.append(f"  {task.name}_daemon.Start();")
    lines += [
        f"  TaskHooks<{task.name}_tag>::init({p1}, {p2}, {p3});",
        "  std::uint64_t last_us = NowUs();",
        f"  LoopContext context{{{p1}, {p2}, {p3}, {daemon}, 0.0F,",
        f"                      {task.period_us or 0}U, last_us, 0U}};",
    ]
    if task.period_us is not None:
        lines += [
            "  LibXR::MillisecondTimestamp wake_time(",
            "      static_cast<std::uint32_t>(LibXR::Timebase::GetMilliseconds()));",
            "  for (;;)",
            "  {",
            f"    LibXR::Thread::SleepUntil(wake_time, {task.period_us // 1000}U);",
        ]
    else:
        lines += [
            "  for (;;)",
            "  {",
            f"    static_cast<void>(::{task.trigger_sem}.Wait());",
        ]
    lines += [
        "    context.now_us = NowUs();",
        "    context.dt_s = static_cast<float>(context.now_us - last_us) * 1.0e-6F;",
        "    last_us = context.now_us;",
        f"    TaskHooks<{task.name}_tag>::loop(context);",
        "    ++context.iteration;",
        "  }",
        "}",
        "",
    ]
    return lines


def make_source(tasks: list[Task]) -> str:
    lines = [
        "// Generated by generate_task.py. Do not edit.",
        '#include "task_generated.hpp"',
        "",
        '#include "timebase.hpp"',
        "",
        "namespace generated::task",
        "{",
        "namespace",
        "{",
        "std::uint64_t NowUs()",
        "{",
        "  return static_cast<std::uint64_t>(LibXR::Timebase::GetMicroseconds());",
        "}",
        "",
    ]
    for task in tasks:
        if task.daemon_timeout_ms is not None:
            lines.append(
                f'DaemonService {task.name}_daemon("{task.name}", {task.daemon_timeout_ms}U);'
            )
    lines += ["}  // namespace", ""]
    for task in tasks:
        lines += [f"LibXR::Thread {task.name}_thread;", ""]
        lines += task_entry(task)
    lines += [
        "}  // namespace generated::task",
        "",
        "void all_tasks_start()",
        "{",
        "  static bool started = false;",
        "  if (started)",
        "  {",
        "    return;",
        "  }",
        "  started = true;",
        "  generated::task::TaskDaemon::Instance().Start();",
    ]
    for task in tasks:
        lines += [
            f"  generated::task::{task.name}_thread.Create(",
            f"      static_cast<void*>(nullptr), generated::task::{task.entry_function},",
            f'      "{task.name}", {task.stack_size}U, {PRIORITIES[task.priority]});',
        ]
    lines += ["}", ""]
    return "\n".join(lines)


def write_if_changed(path: Path, content: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    if path.exists() and path.read_text(encoding="utf-8") == content:
        return
    path.write_text(content, encoding="utf-8", newline="\n")


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("config", type=Path)
    parser.add_argument("output_dir", type=Path)
    args = parser.parse_args()
    try:
        document = tomllib.loads(args.config.read_text(encoding="utf-8"))
        raw_tasks = document.get("tasks", [])
        if not isinstance(raw_tasks, list):
            raise ValueError("'tasks' must be an array of tables")
        tasks = [parse_task(raw) for raw in raw_tasks]
        if len({task.name for task in tasks}) != len(tasks):
            raise ValueError("task names must be unique")
        if len({task.entry_function for task in tasks}) != len(tasks):
            raise ValueError("entry_function values must be unique")
        write_if_changed(args.output_dir / "task_generated.hpp", make_header(tasks))
        write_if_changed(args.output_dir / "task_generated.cc", make_source(tasks))
    except (OSError, ValueError, tomllib.TOMLDecodeError) as error:
        print(f"task generator: {error}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
